-- 98: Müşteri destek hattı
-- Kullanıcı ile destek ekibi arasında sohbet (talep), temsilci gelen kutusu ve
-- yönetici tarafından temsilci tanımlama.
-- Yalnızca ekleme yapar: yeni tablolar, yeni fonksiyonlar, bir RLS okuma politikası
-- ve support_messages tablosunun realtime yayına eklenmesi. Mevcut tablolara ve
-- verilere dokunmaz.

-- ---------------------------------------------------------------- tablolar
create table if not exists public.support_agents (
  user_id      uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (char_length(btrim(display_name)) between 2 and 40),
  active       boolean not null default true,
  created_at   timestamptz not null default now(),
  created_by   uuid
);

create table if not exists public.support_presence (
  user_id   uuid primary key references auth.users(id) on delete cascade,
  last_seen timestamptz not null default now()
);

create table if not exists public.support_tickets (
  id            bigint generated by default as identity (start with 1001) primary key,
  user_id       uuid not null references auth.users(id) on delete cascade,
  topic         text not null default 'Genel' check (char_length(topic) between 1 and 40),
  status        text not null default 'open' check (status in ('open', 'answered', 'closed')),
  assigned_to   uuid references auth.users(id) on delete set null,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  closed_at     timestamptz,
  closed_by     uuid,
  user_read_id  bigint not null default 0,
  agent_read_id bigint not null default 0,
  user_seen_at  timestamptz,
  agent_seen_at timestamptz,
  rating        smallint check (rating between 1 and 5),
  rated_at      timestamptz
);
-- Bir kullanıcının aynı anda tek açık talebi olur.
create unique index if not exists support_tickets_one_active on public.support_tickets (user_id) where status <> 'closed';
create index if not exists support_tickets_status_idx on public.support_tickets (status, updated_at desc);
create index if not exists support_tickets_user_idx on public.support_tickets (user_id, id desc);

create table if not exists public.support_messages (
  id         bigint generated by default as identity primary key,
  ticket_id  bigint not null references public.support_tickets(id) on delete cascade,
  user_id    uuid not null references auth.users(id) on delete cascade, -- talebin sahibi
  kind       text not null check (kind in ('user', 'agent', 'system')),
  body       text not null check (char_length(body) between 1 and 2000),
  agent_name text,
  created_at timestamptz not null default now()
);
create index if not exists support_messages_user_idx on public.support_messages (user_id, id);
create index if not exists support_messages_ticket_idx on public.support_messages (ticket_id, id);

-- Temsilci mesajını kimin yazdığı (kullanıcıya açık değil, denetim için).
create table if not exists public.support_message_authors (
  message_id bigint primary key references public.support_messages(id) on delete cascade,
  sender     uuid not null
);

alter table public.support_agents          enable row level security;
alter table public.support_presence        enable row level security;
alter table public.support_tickets         enable row level security;
alter table public.support_messages        enable row level security;
alter table public.support_message_authors enable row level security;

revoke all on table public.support_agents, public.support_presence, public.support_tickets,
  public.support_messages, public.support_message_authors from anon, authenticated;
-- Mesajlar yalnızca okunabilir (realtime için); yazma işlemleri fonksiyonlardan yapılır.
grant select on table public.support_messages to authenticated;

-- ---------------------------------------------------------------- yetki
create or replace function public.is_support_agent()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.support_agents a where a.user_id = auth.uid() and a.active)
      or exists (select 1 from public.profiles p where p.id = auth.uid() and p.is_admin);
$$;

do $$ begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'support_messages'
                 and policyname = 'destek mesajlarini oku') then
    create policy "destek mesajlarini oku" on public.support_messages for select to authenticated
      using (user_id = (select auth.uid()) or (select public.is_support_agent()));
  end if;
end $$;

do $$ begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime'
                     and schemaname = 'public' and tablename = 'support_messages') then
    alter publication supabase_realtime add table public.support_messages;
  end if;
end $$;

-- ---------------------------------------------------------------- yardımcılar
create or replace function cf_private.support_agent_name(p_uid uuid)
returns text language sql stable security definer set search_path = public as $$
  select coalesce((select a.display_name from public.support_agents a where a.user_id = p_uid and a.active),
                  'COINFORCE Destek');
$$;

create or replace function cf_private.support_online()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.support_presence s where s.last_seen > now() - interval '5 minutes');
$$;

create or replace function cf_private.support_seen(p_uid uuid)
returns void language sql security definer set search_path = public as $$
  insert into public.support_presence as s (user_id, last_seen) values (p_uid, now())
  on conflict (user_id) do update set last_seen = excluded.last_seen
   where s.last_seen < now() - interval '30 seconds';
$$;

create or replace function cf_private.support_notify_agents(p_body text)
returns void language sql security definer set search_path = public as $$
  insert into public.notifications (user_id, body)
  select s.u, p_body from (
    select a.user_id as u from public.support_agents a where a.active
    union
    select p.id from public.profiles p where p.is_admin
  ) s;
$$;

-- ---------------------------------------------------------------- kullanıcı
create or replace function public.support_badge()
returns json language plpgsql stable security definer set search_path = public as $$
declare v_uid uuid := auth.uid(); v_agent boolean; v_unread int := 0; v_wait int := 0;
begin
  if v_uid is null then
    return json_build_object('agent', false, 'admin', false, 'unread', 0, 'waiting', 0);
  end if;
  v_agent := public.is_support_agent();
  select count(*) into v_unread
    from public.support_messages m join public.support_tickets t on t.id = m.ticket_id
   where t.user_id = v_uid and m.kind = 'agent' and m.id > t.user_read_id;
  if v_agent then
    select count(*) into v_wait from public.support_tickets where status = 'open';
  end if;
  return json_build_object('agent', v_agent,
    'admin', exists (select 1 from public.profiles where id = v_uid and is_admin),
    'unread', v_unread, 'waiting', v_wait);
end $$;

create or replace function public.support_thread(p_after bigint default 0)
returns json language plpgsql security definer set search_path = public as $$
declare v_uid uuid := auth.uid(); v_t public.support_tickets; v_max bigint; v_msgs json;
begin
  if v_uid is null then raise exception 'Oturum açmalısın'; end if;
  select * into v_t from public.support_tickets where user_id = v_uid order by id desc limit 1;
  select coalesce(json_agg(x order by x.id), '[]'::json) into v_msgs from (
    select m.id, m.ticket_id as ticket, m.kind, m.body, m.agent_name as agent, m.created_at as at
      from public.support_messages m
     where m.user_id = v_uid and m.id > coalesce(p_after, 0)
     order by m.id desc limit 300) x;
  if v_t.id is not null then
    select max(m.id) into v_max from public.support_messages m where m.ticket_id = v_t.id;
    if v_t.user_read_id < coalesce(v_max, 0) or v_t.user_seen_at is null
       or v_t.user_seen_at < now() - interval '10 seconds' then
      update public.support_tickets
         set user_read_id = greatest(user_read_id, coalesce(v_max, 0)), user_seen_at = now()
       where id = v_t.id;
    end if;
  end if;
  return json_build_object(
    'ticket', case when v_t.id is null then null else json_build_object(
      'id', v_t.id, 'status', v_t.status, 'topic', v_t.topic, 'created_at', v_t.created_at,
      'closed_at', v_t.closed_at, 'agent_read', v_t.agent_read_id, 'rating', v_t.rating) end,
    'messages', v_msgs,
    'online', cf_private.support_online(),
    'now', now());
end $$;

create or replace function public.support_send(p_body text, p_topic text default null)
returns json language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid(); v_body text := btrim(coalesce(p_body, ''));
  v_t public.support_tickets; v_new boolean := false; v_id bigint; v_n int; v_topic text;
begin
  if v_uid is null then raise exception 'Oturum açmalısın'; end if;
  if v_body = '' then raise exception 'Mesaj boş olamaz'; end if;
  if char_length(v_body) > 2000 then raise exception 'Mesaj en fazla 2000 karakter olabilir'; end if;
  select count(*) into v_n from public.support_messages
   where user_id = v_uid and kind = 'user' and created_at > now() - interval '1 minute';
  if v_n >= 10 then raise exception 'Çok hızlı mesaj gönderiyorsun. Lütfen biraz bekle.'; end if;
  select count(*) into v_n from public.support_messages
   where user_id = v_uid and kind = 'user' and created_at > now() - interval '1 day';
  if v_n >= 200 then raise exception 'Bugünkü mesaj sınırına ulaştın. Ekibimiz mevcut mesajlarını yanıtlayacak.'; end if;

  select * into v_t from public.support_tickets where user_id = v_uid and status <> 'closed' for update;
  if v_t.id is null then
    v_topic := case when p_topic in ('Para yatırma', 'Para çekme', 'Kimlik doğrulama', 'İşlem ve emirler',
                                     'Hesap değerlendirme', 'Hesap ve güvenlik', 'Diğer')
                    then p_topic else 'Genel' end;
    begin
      insert into public.support_tickets (user_id, topic) values (v_uid, v_topic) returning * into v_t;
      v_new := true;
    exception when unique_violation then
      select * into v_t from public.support_tickets where user_id = v_uid and status <> 'closed' for update;
    end;
  end if;

  insert into public.support_messages (ticket_id, user_id, kind, body)
  values (v_t.id, v_uid, 'user', v_body) returning id into v_id;

  if v_new then
    insert into public.support_messages (ticket_id, user_id, kind, body) values (v_t.id, v_uid, 'system', 'ticket_open');
    perform cf_private.support_notify_agents(format('🎧 Yeni destek talebi #%s · %s', v_t.id, v_t.topic));
  elsif v_t.status = 'answered' and v_t.assigned_to is not null
        and (v_t.agent_seen_at is null or v_t.agent_seen_at < now() - interval '25 seconds') then
    perform public._notify(v_t.assigned_to, format('💬 Destek talebi #%s için kullanıcıdan yeni mesaj var', v_t.id));
  end if;

  update public.support_tickets
     set status = 'open', updated_at = now(), user_read_id = greatest(user_read_id, v_id), user_seen_at = now()
   where id = v_t.id;
  return json_build_object('id', v_id, 'ticket', v_t.id, 'new', v_new);
end $$;

create or replace function public.support_user_close()
returns json language plpgsql security definer set search_path = public as $$
declare v_uid uuid := auth.uid(); v_t public.support_tickets;
begin
  if v_uid is null then raise exception 'Oturum açmalısın'; end if;
  select * into v_t from public.support_tickets where user_id = v_uid and status <> 'closed' for update;
  if v_t.id is null then return json_build_object('ok', true, 'ticket', null); end if;
  update public.support_tickets set status = 'closed', closed_at = now(), closed_by = v_uid, updated_at = now()
   where id = v_t.id;
  insert into public.support_messages (ticket_id, user_id, kind, body) values (v_t.id, v_uid, 'system', 'user_closed');
  return json_build_object('ok', true, 'ticket', v_t.id);
end $$;

create or replace function public.support_rate(p_ticket bigint, p_rating int)
returns json language plpgsql security definer set search_path = public as $$
declare v_uid uuid := auth.uid();
begin
  if v_uid is null then raise exception 'Oturum açmalısın'; end if;
  if p_rating is null or p_rating < 1 or p_rating > 5 then raise exception 'Puan 1 ile 5 arasında olmalı'; end if;
  update public.support_tickets set rating = p_rating, rated_at = now()
   where id = p_ticket and user_id = v_uid and status = 'closed' and rating is null;
  if not found then raise exception 'Bu talep puanlanamaz'; end if;
  return json_build_object('ok', true);
end $$;

-- ---------------------------------------------------------------- temsilci
create or replace function public.support_inbox(p_filter text default 'open')
returns json language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_f text := case when p_filter in ('open', 'answered', 'closed') then p_filter else 'open' end;
begin
  if not public.is_support_agent() then raise exception 'Bu bölüm sadece destek ekibi içindir'; end if;
  perform cf_private.support_seen(v_uid);
  return json_build_object(
    'counts', (select json_build_object(
        'open', count(*) filter (where status = 'open'),
        'answered', count(*) filter (where status = 'answered'),
        'closed', count(*) filter (where status = 'closed' and closed_at > now() - interval '30 days'))
      from public.support_tickets),
    'items', (select coalesce(json_agg(x order by x.ord), '[]'::json) from (
      select y.*, row_number() over (order by case when v_f = 'open'
               then extract(epoch from coalesce(y.waiting_since, y.updated_at))
               else -extract(epoch from y.updated_at) end) as ord
        from (
          select t.id, t.status, t.topic, t.created_at, t.updated_at, t.closed_at, t.rating,
                 p.username, p.full_name,
                 case when t.assigned_to is null then null else cf_private.support_agent_name(t.assigned_to) end as agent,
                 (select json_build_object('kind', m.kind, 'body', left(m.body, 140), 'agent', m.agent_name, 'at', m.created_at)
                    from public.support_messages m
                   where m.ticket_id = t.id and m.kind <> 'system' order by m.id desc limit 1) as last,
                 (select count(*) from public.support_messages m
                   where m.ticket_id = t.id and m.kind = 'user' and m.id > t.agent_read_id) as unread,
                 (select min(m.created_at) from public.support_messages m
                   where m.ticket_id = t.id and m.kind = 'user'
                     and m.id > coalesce((select max(a.id) from public.support_messages a
                                           where a.ticket_id = t.id and a.kind = 'agent'), 0)) as waiting_since
            from public.support_tickets t
            left join public.profiles p on p.id = t.user_id
           where t.status = v_f and (v_f <> 'closed' or t.closed_at > now() - interval '30 days')
        ) y
       order by ord limit 100) x),
    'me', json_build_object('admin', exists (select 1 from public.profiles where id = v_uid and is_admin),
                            'name', cf_private.support_agent_name(v_uid)),
    'now', now());
end $$;

create or replace function public.support_ticket(p_ticket bigint, p_after bigint default 0)
returns json language plpgsql security definer set search_path = public as $$
declare v_uid uuid := auth.uid(); v_t public.support_tickets; v_max bigint; v_msgs json; v_u record;
begin
  if not public.is_support_agent() then raise exception 'Bu bölüm sadece destek ekibi içindir'; end if;
  select * into v_t from public.support_tickets where id = p_ticket;
  if v_t.id is null then raise exception 'Talep bulunamadı'; end if;
  perform cf_private.support_seen(v_uid);
  -- Bu talep ve kullanıcının önceki talepleri (geçmiş bağlam)
  select coalesce(json_agg(x order by x.id), '[]'::json) into v_msgs from (
    select m.id, m.ticket_id as ticket, m.kind, m.body, m.agent_name as agent, m.created_at as at
      from public.support_messages m
     where m.user_id = v_t.user_id and m.ticket_id <= v_t.id and m.id > coalesce(p_after, 0)
     order by m.id desc limit 300) x;
  select max(m.id) into v_max from public.support_messages m where m.ticket_id = v_t.id;
  if v_t.agent_read_id < coalesce(v_max, 0) or v_t.agent_seen_at is null
     or v_t.agent_seen_at < now() - interval '10 seconds' then
    update public.support_tickets
       set agent_read_id = greatest(agent_read_id, coalesce(v_max, 0)), agent_seen_at = now()
     where id = v_t.id;
  end if;
  select p.username, p.full_name, p.created_at into v_u from public.profiles p where p.id = v_t.user_id;
  return json_build_object(
    'ticket', json_build_object(
      'id', v_t.id, 'status', v_t.status, 'topic', v_t.topic, 'created_at', v_t.created_at,
      'closed_at', v_t.closed_at, 'rating', v_t.rating, 'user_id', v_t.user_id,
      'username', v_u.username, 'full_name', v_u.full_name, 'joined', v_u.created_at,
      'review', exists (select 1 from public.account_reviews r where r.user_id = v_t.user_id and r.status = 'pending'),
      'tickets', (select count(*) from public.support_tickets s where s.user_id = v_t.user_id),
      'agent', case when v_t.assigned_to is null then null else cf_private.support_agent_name(v_t.assigned_to) end),
    'messages', v_msgs,
    'me', cf_private.support_agent_name(v_uid),
    'now', now());
end $$;

create or replace function public.support_reply(p_ticket bigint, p_body text)
returns json language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid(); v_body text := btrim(coalesce(p_body, ''));
  v_t public.support_tickets; v_name text; v_id bigint; v_recent boolean;
begin
  if not public.is_support_agent() then raise exception 'Bu bölüm sadece destek ekibi içindir'; end if;
  if v_body = '' then raise exception 'Mesaj boş olamaz'; end if;
  if char_length(v_body) > 2000 then raise exception 'Mesaj en fazla 2000 karakter olabilir'; end if;
  select * into v_t from public.support_tickets where id = p_ticket for update;
  if v_t.id is null then raise exception 'Talep bulunamadı'; end if;
  if v_t.status = 'closed' then raise exception 'Bu talep kapatılmış. Kullanıcı yeniden yazarsa yeni talep açılır.'; end if;
  v_name := cf_private.support_agent_name(v_uid);
  -- Son 2 dakikada zaten bir temsilci mesajı varsa kullanıcıya tekrar bildirim gönderme.
  v_recent := exists (select 1 from public.support_messages m where m.ticket_id = v_t.id and m.kind = 'agent'
                       and m.created_at > now() - interval '2 minutes'
                       and m.id > coalesce((select max(u.id) from public.support_messages u
                                             where u.ticket_id = v_t.id and u.kind = 'user'), 0));
  if v_t.assigned_to is null then
    insert into public.support_messages (ticket_id, user_id, kind, body, agent_name)
    values (v_t.id, v_t.user_id, 'system', 'agent_join', v_name);
  end if;
  insert into public.support_messages (ticket_id, user_id, kind, body, agent_name)
  values (v_t.id, v_t.user_id, 'agent', v_body, v_name) returning id into v_id;
  insert into public.support_message_authors (message_id, sender) values (v_id, v_uid);
  update public.support_tickets
     set status = 'answered', assigned_to = coalesce(assigned_to, v_uid), updated_at = now(),
         agent_read_id = greatest(agent_read_id, v_id), agent_seen_at = now()
   where id = v_t.id;
  perform cf_private.support_seen(v_uid);
  if not v_recent and (v_t.user_seen_at is null or v_t.user_seen_at < now() - interval '25 seconds') then
    perform public._notify(v_t.user_id, '💬 Destek ekibi mesajınızı yanıtladı. Uygulamadaki Destek bölümünden okuyabilirsiniz.');
  end if;
  return json_build_object('id', v_id, 'ticket', v_t.id);
end $$;

create or replace function public.support_close(p_ticket bigint)
returns json language plpgsql security definer set search_path = public as $$
declare v_uid uuid := auth.uid(); v_t public.support_tickets;
begin
  if not public.is_support_agent() then raise exception 'Bu bölüm sadece destek ekibi içindir'; end if;
  select * into v_t from public.support_tickets where id = p_ticket for update;
  if v_t.id is null then raise exception 'Talep bulunamadı'; end if;
  if v_t.status = 'closed' then return json_build_object('ok', true, 'already', true); end if;
  update public.support_tickets
     set status = 'closed', closed_at = now(), closed_by = v_uid, updated_at = now(),
         assigned_to = coalesce(assigned_to, v_uid)
   where id = v_t.id;
  insert into public.support_messages (ticket_id, user_id, kind, body, agent_name)
  values (v_t.id, v_t.user_id, 'system', 'ticket_closed', cf_private.support_agent_name(v_uid));
  if v_t.user_seen_at is null or v_t.user_seen_at < now() - interval '25 seconds' then
    perform public._notify(v_t.user_id,
      format('✅ Destek talebiniz #%s çözüldü olarak kapatıldı. Deneyiminizi puanlayabilirsiniz.', v_t.id));
  end if;
  return json_build_object('ok', true);
end $$;

-- ---------------------------------------------------------------- yönetici
create or replace function public.admin_support_agents()
returns json language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Bu işlem sadece yönetici içindir'; end if;
  return (select coalesce(json_agg(x order by x.active desc, x.created_at), '[]'::json) from (
    select a.user_id, p.username, a.display_name, a.active, a.created_at, s.last_seen
      from public.support_agents a
      left join public.profiles p on p.id = a.user_id
      left join public.support_presence s on s.user_id = a.user_id) x);
end $$;

create or replace function public.admin_support_agent_set(p_username text, p_display_name text default null,
                                                          p_active boolean default true)
returns json language plpgsql security definer set search_path = public as $$
declare v_p record; v_name text := nullif(btrim(coalesce(p_display_name, '')), '');
begin
  if not public.is_admin() then raise exception 'Bu işlem sadece yönetici içindir'; end if;
  select p.id, p.username, p.full_name into v_p from public.profiles p
   where lower(p.username) = lower(btrim(coalesce(p_username, '')))
   order by (p.username = btrim(p_username)) desc limit 1;
  if v_p.id is null then raise exception 'Kullanıcı bulunamadı: %', p_username; end if;
  insert into public.support_agents (user_id, display_name, active, created_by)
  values (v_p.id,
          coalesce(v_name, nullif(split_part(btrim(coalesce(v_p.full_name, '')), ' ', 1), ''), v_p.username),
          coalesce(p_active, true), auth.uid())
  on conflict (user_id) do update
     set active = excluded.active,
         display_name = coalesce(v_name, public.support_agents.display_name);
  return json_build_object('ok', true, 'user_id', v_p.id, 'username', v_p.username);
end $$;

